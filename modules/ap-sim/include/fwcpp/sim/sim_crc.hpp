inline std::uint8_t crc8_dvb(std::uint8_t crc, std::uint8_t a, std::uint8_t seed) {
    crc ^= a;
    for (std::uint8_t i = 0; i < 8; ++i) {
        if (crc & 0x80) {
            crc = static_cast<std::uint8_t>((crc << 1) ^ seed);
        } else {
            crc = static_cast<std::uint8_t>(crc << 1);
        }
    }
    return crc;
}

inline std::uint8_t crc8_dvb_s2(std::uint8_t crc, std::uint8_t a) {
    return crc8_dvb(crc, a, 0xD5);
}

inline std::uint8_t crc8_dvb_s2_update(std::uint8_t crc, const void* data, std::uint32_t length) {
    const auto* p = static_cast<const std::uint8_t*>(data);
    const auto* pend = p + length;
    for (; p != pend; ++p) {
        crc = crc8_dvb_s2(crc, *p);
    }
    return crc;
}

inline std::uint32_t crc_crc32(std::uint32_t crc, const std::uint8_t* buf, std::uint32_t size) {
    while (size--) {
        const std::uint8_t byte = *buf++;
        crc ^= byte;
        for (std::uint8_t i = 0; i < 8; i++) {
            const std::uint32_t mask = -(crc & 1U);
            crc >>= 1;
            crc ^= (0xEDB88320U & mask);
        }
    }
    return crc;
}

