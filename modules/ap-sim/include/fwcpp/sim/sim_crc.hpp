inline std::uint16_t calc_crc_modbus(const std::uint8_t* buf, std::uint16_t len) {
    std::uint16_t crc = 0xFFFF;
    for (std::uint16_t pos = 0; pos < len; pos++) {
        crc ^= static_cast<std::uint16_t>(buf[pos]);
        for (std::uint8_t i = 8; i != 0; i--) {
            if ((crc & 0x0001) != 0) {
                crc >>= 1;
                crc ^= 0xA001;
            } else {
                crc >>= 1;
            }
        }
    }
    return crc;
}

inline std::uint16_t crc16_ccitt_r(const std::uint8_t* buf, std::uint32_t len, std::uint16_t crc, std::uint16_t outv) {
    for (std::uint32_t i = 0; i < len; i++) {
        crc ^= *buf++;
        for (std::uint8_t j = 0; j < 8; j++) {
            if ((crc & 0x0001) != 0) {
                crc = static_cast<std::uint16_t>((crc >> 1) ^ 0x8408);
            } else {
                crc >>= 1;
            }
        }
    }
    return static_cast<std::uint16_t>(crc ^ outv);
}

inline std::uint8_t crc8_rds02uf(const std::uint8_t* data, std::uint16_t length) {
    std::uint8_t crc = 0;
    while (length--) {
        crc ^= *data++;
        for (std::uint8_t i = 0; i < 8; i++) {
            if (crc & 0x80) {
                crc = static_cast<std::uint8_t>((crc << 1) ^ 0x07);
            } else {
                crc = static_cast<std::uint8_t>(crc << 1);
            }
        }
    }
    return crc;
}


inline std::uint16_t crc_xmodem_update(std::uint16_t crc, std::uint8_t data) {
    return crc16_ccitt(&data, 1, crc);
}

inline std::uint8_t crc8_generic_poly(const std::uint8_t* data, std::uint8_t len, std::uint8_t poly,
                                      std::uint8_t crc = 0) {
    while (len--) {
        crc ^= *data++;
        for (std::uint8_t i = 0; i < 8; i++) {
            if (crc & 0x80) {
                crc = static_cast<std::uint8_t>((crc << 1) ^ poly);
            } else {
                crc = static_cast<std::uint8_t>(crc << 1);
            }
        }
    }
    return crc;
}


