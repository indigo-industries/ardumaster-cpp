inline std::uint16_t crc_sum_of_bytes_16(const std::uint8_t* data, std::uint16_t count) {
    std::uint16_t sum = 0;
    while (count--) {
        sum = static_cast<std::uint16_t>(sum + *data++);
    }
    return sum;
}

inline std::uint8_t crc_sum_of_bytes(const std::uint8_t* data, std::uint16_t count) {
    return static_cast<std::uint8_t>(crc_sum_of_bytes_16(data, count) & 0xFF);
}

